function idea(
  id: string,
  symbol: string,
  company: string,
  option: OptionContract,
  fields: Omit<Idea, 'id' | 'symbol' | 'company' | 'assetType' | 'option' | 'contractDetail'>,
): Idea {
  return {
    id,
    source:
      id === 'idea-avgo-jan' || id === 'idea-coin-put' || id === 'idea-arm-dec'
        ? 'user'
        : 'ai',
    symbol,
    company,
    assetType: 'option',
    option,
    contractDetail: `$${option.strike} ${option.right === 'CALL' ? 'Call' : 'Put'} · ${option.expiryLabel}`,
    ...fields,
  }
}

